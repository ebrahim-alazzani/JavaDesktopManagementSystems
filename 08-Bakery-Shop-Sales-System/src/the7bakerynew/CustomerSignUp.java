    public void add() {
        int result = 0;

        if (txtFname.getText().equals("") || txtLname.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Please make sure that none of the fields are blank.", "Entry Error", 1);
        } else {
            customer.setFname(txtFname.getText());
            customer.setLname(txtLname.getText());
            customer.setEmail(txtEmail1.getText());
            customer.setPhone_No(txtPhone_No.getText());
            customer.setUserName(txtUserName.getText());
            customer.setCPassword(txtPassword.getText());
            try {
                if (ds.InsertCustomer(customer) == 1) {
                    //tableemp();
                    JOptionPane.showMessageDialog(this, "Records inserted successfully.", "Entry Error", 1);
                } else {
                    JOptionPane.showMessageDialog(this, "Records insertion failed.", "Entry Error", 1);
                }

                //   con.close();
            } catch (SQLException ex) {
                Logger.getLogger(com.mycompany.the7bakerapp.ItemsOp.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }

