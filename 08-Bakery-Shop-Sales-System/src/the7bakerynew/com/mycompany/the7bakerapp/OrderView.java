    public void tableemp() {
        //new DefaultTableModel(new String[] {"id","name","price","Qty","Total"},0);
        DefaultTableModel model = new DefaultTableModel(new Object[]{"OrderId", "CustomerId", "Date","Total"
        }, 0);
        list = ds.SelectOrder();
        Object rowdata[] = new Object[4];
        //System.out.println("size" + list.size());
        for (int i = 0; i < list.size(); i++) {
            rowdata[0] = list.get(i).getOrder_ID();
            rowdata[1] = list.get(i).getCustomer().getCustomer_ID();
            rowdata[2] = list.get(i).getOrderDate();
            rowdata[3]=list.get(i).getTotal();

            model.addRow(rowdata);
        }

        jTable1.setModel(model);
    }

    public void tableOrderItem(int orderId) {
        //new DefaultTableModel(new String[] {"id","name","price","Qty","Total"},0);
        DefaultTableModel model = new DefaultTableModel(new Object[]{"Id", "Price Unit", "Item Id",
            "Item Name","Price Total","Quangtity"
        }, 0);
        ArrayList<Order_Info> listOrddr = ds.SelectOrderItems(orderId);
        Object rowdata[] = new Object[7];
        //System.out.println("size" + list.size());
        for (int i = 0; i < listOrddr.size(); i++) {
            rowdata[0] = listOrddr.get(i).getOrder_Info_ID();
            rowdata[1] = listOrddr.get(i).getItem_price();
            rowdata[2] = listOrddr.get(i).getItems().getItem_ID();
            rowdata[3] = listOrddr.get(i).getItems().getName();
            rowdata[4] = listOrddr.get(i).getItems().getPrice();
            rowdata[5] = listOrddr.get(i).getItems().getQuantity();
       

            model.addRow(rowdata);
        }

        jTable2.setModel(model);
    }

