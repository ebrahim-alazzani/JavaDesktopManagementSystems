    public void tableCustomer()  {
        //new DefaultTableModel(new String[] {"id","name","price","Qty","Total"},0);
        DefaultTableModel model = new DefaultTableModel(new Object[]{"Id", "Fname", "Lname", "Email", "phone"
        }, 0);
        try {
            list = ds.getUserAll();
        } catch (SQLException ex) {
            Logger.getLogger(CustomerView.class.getName()).log(Level.SEVERE, null, ex);
        }
        Object rowdata[] = new Object[5];
        //System.out.println("size" + list.size());
        for (int i = 0; i < list.size(); i++) {
            rowdata[0] = list.get(i).getCustomer_ID();
            rowdata[1] = list.get(i).getFname();
            rowdata[2] = list.get(i).getLname();
            rowdata[3] = list.get(i).getEmail();
            rowdata[4] = list.get(i).getPhone_No();

            model.addRow(rowdata);
        }

        jTable1.setModel(model);
    }

