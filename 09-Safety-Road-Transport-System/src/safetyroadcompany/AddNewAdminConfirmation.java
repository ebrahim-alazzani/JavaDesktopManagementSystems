    public void addAdmin() throws SQLException {
        int result = 0;
        String email = jtxtEmail.getText();
        String regEx = "\\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,4}\\b";
        Pattern p = Pattern.compile(regEx);
        Matcher m = p.matcher(email);

        if (jtxtID.getText().equals("") || jtxtName.getText().equals("")
                || jtxtEmail.getText().equals("") || jtxtPassword.getText().equals("")
                || jtxtPhoneNumber.getText().equals("") || jtxtUserName.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Please make sure that none of the fields are blank.", "Entry Error", 1);

        } else if (!m.find()) {
            JOptionPane.showMessageDialog(null, "invalid email!", "warning", JOptionPane.WARNING_MESSAGE);

        } else {

            admin = new Admin(Integer.parseInt(jtxtID.getText()), jtxtName.getText(), jtxtEmail.getText(),
                    jtxtPassword.getText(), jtxtUserName.getText(), jtxtPhoneNumber.getText(), 1);

            if (ds.InsertAdmin(admin) == 1) {
                JOptionPane.showMessageDialog(this, "Records inserted successfully.", "Entry Error", 1);
            } else {
                JOptionPane.showMessageDialog(this, "Records insertion failed.", "Entry Error", 1);
            }

            //   con.close();
        }
    }

