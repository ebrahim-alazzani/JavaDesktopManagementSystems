    private void add_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_add_btnActionPerformed
       int state = 1;
        if(t_name.getText() == null || t_capatiy.getText() == null
                || t_state.getText() == null){
                JOptionPane.showMessageDialog(this, "Please make sure that none of the fields are blank.", "Entry Error", JOptionPane.WARNING_MESSAGE);
        }else{
            state = Integer.valueOf( t_state.getText());
        this.ds.inserttable(t_name.getText(), Integer.valueOf( t_capatiy.getText()),state);
        this.ds.select_table(jTable2);
        clear1();
        } // TODO add your handling code here:
    }//GEN-LAST:event_add_btnActionPerformed

