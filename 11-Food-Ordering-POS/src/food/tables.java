    private void jTable2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable2MouseClicked
      
        DefaultTableModel model =(DefaultTableModel)jTable2.getModel();
        updateb.setEnabled(true); 
        del.setEnabled(true); 
        int selectitem=jTable2.getSelectedRow();
        t_id.setText(model.getValueAt(selectitem,0).toString());

        t_name.setText(model.getValueAt(selectitem,1).toString());
        t_capatiy.setText(model.getValueAt(selectitem,2).toString());
        t_state.setText(model.getValueAt(selectitem,3).toString());
         add_btn.setEnabled(false); 
        
// TODO add your handling code here:
    }//GEN-LAST:event_jTable2MouseClicked

